import { describe, it, expect } from "vitest";
import { ChunkedFile, EOFError } from "./helpers/chunked-file.js";
import { encode, encodeToInternational, decode } from "../src/codec.js";
import { Point } from "../src/point.js";
import { Mapcode } from "../src/mapcode.js";
import { Territory } from "../src/territory.js";
import { UnknownMapcodeError } from "../src/errors.js";

// ----------------------------------------------------------------------------------------------
// Faithful port of com.mapcode.ReferenceFileTest. Validates encode/decode against the full set
// of reference vectors generated by the reference C++ implementation. Runs sequentially (no
// thread pool); accumulates an error count and asserts it is zero.
// ----------------------------------------------------------------------------------------------

const PRECISION_MAX = 8;
const LOG_LINE_EVERY = 10000;

const RANDOM_REFERENCE_FILE_1 = "random_e8_1k.txt";
const RANDOM_REFERENCE_FILE_2 = "random_e8_10k.txt";
const RANDOM_REFERENCE_FILE_3 = "random_e8_100k.txt";
const GRID_REFERENCE_FILE_1 = "grid_e8_1k.txt";
const GRID_REFERENCE_FILE_2 = "grid_e8_10k.txt";
const GRID_REFERENCE_FILE_3 = "grid_e8_100k.txt";
const BOUNDARIES_REFERENCE_FILE = "boundaries_e8.txt";

interface MapcodeRec {
  readonly mapcode: string;
  readonly territory: Territory;
}

interface ReferenceRec {
  readonly point: Point;
  readonly mapcodes: MapcodeRec[];
}

function getNextReferenceRecord(chunkedFile: ChunkedFile): ReferenceRec {
  // Read first line of data file: <nr> <lat> <lon> [<x> <y> <z>]
  const firstLine = chunkedFile.readNonEmptyLine();
  const args = firstLine.split(" ");
  if (args.length !== 3 && args.length !== 6) {
    throw new Error("Expecting 3 or 6 elements, not " + args.length + " in line: " + firstLine);
  }

  const count = Number.parseInt(args[0], 10);
  if (!(count >= 1 && count <= 22)) {
    throw new Error("Expecting between 1 and 22 mapcodes, got " + count);
  }

  // Read lat/lon.
  const latDeg = Number.parseFloat(args[1]);
  const lonDeg = Number.parseFloat(args[2]);
  const point = Point.fromDeg(latDeg, lonDeg);
  if (!(point.getLatDeg() >= -90 && point.getLatDeg() <= 90)) {
    throw new Error("Latitude must be in [-90, 90]: " + point.getLatDeg());
  }
  if (!(point.getLonDeg() >= -180 && point.getLonDeg() <= 180)) {
    throw new Error("Longitude must be in [-180, 180]: " + point.getLonDeg());
  }

  // Read mapcodes: [<territory>] <mapcode>
  const mapcodeRecs: MapcodeRec[] = [];
  for (let i = 0; i < count; ++i) {
    const line = chunkedFile.readNonEmptyLine();
    const mapcodeLine = line.split(" ");
    if (mapcodeLine.length > 2) {
      throw new Error("Expecting 1 or 2 elements, territory and mapcode, got: " + mapcodeLine.length + ", " + line);
    }

    let territory: Territory;
    let mapcode: string;
    if (mapcodeLine.length === 1) {
      territory = Territory.AAA;
      mapcode = mapcodeLine[0];
    } else {
      territory = Territory.fromString(mapcodeLine[0]);
      mapcode = mapcodeLine[1];
    }
    mapcodeRecs.push({ mapcode, territory });
  }
  if (mapcodeRecs.length !== count) {
    throw new Error("Wrong number of mapcodes found");
  }
  return { point, mapcodes: mapcodeRecs };
}

function checkFile(precision: number, baseFileName: string, checkAllDistances: boolean): number {
  if (!(precision >= 0 && precision <= PRECISION_MAX)) {
    throw new Error("precision out of range: " + precision);
  }

  const deltaNm: number[] = new Array(PRECISION_MAX).fill(0);
  let errors = 0;
  let tasks = 0;

  const chunkedFile = new ChunkedFile(baseFileName);
  try {
    for (;;) {
      // Get next record (throws EOFError at end of all chunks).
      let reference: ReferenceRec;
      try {
        reference = getNextReferenceRecord(chunkedFile);
      } catch (e) {
        if (e instanceof EOFError) {
          break;
        }
        throw e;
      }

      const count = tasks++;
      if (count % LOG_LINE_EVERY === 0) {
        // eslint-disable-next-line no-console
        console.log(`checkFile: #${count}, file=${chunkedFile.fileName}, precision=${precision}`);
      }

      const latDeg = reference.point.getLatDeg();
      const lonDeg = reference.point.getLonDeg();

      // Encode lat/lon to series of mapcodes and check the resulting mapcodes.
      const results = encode(latDeg, lonDeg);

      // Check the number of mapcodes.
      if (results.length === 0) {
        console.error(`checkFile: encode fails, no results found for reference=${JSON.stringify(reference.mapcodes)}`);
        errors++;
      }

      // Check if last mapcode is the international code.
      const resultInternational = encodeToInternational(latDeg, lonDeg);
      const expectedInternational = results[results.length - 1];
      if (expectedInternational === undefined || !resultInternational.equals(expectedInternational)) {
        console.error(
          `checkFile: encodeToInternational fails, expected=${expectedInternational}, got=${resultInternational}`,
        );
        errors++;
      }

      // Check the size of the results.
      if (reference.mapcodes.length !== results.length) {
        console.error(
          `checkFile: Incorrect number of results:\n  lat/lon  = ${reference.point}\n` +
            `  expected = #${reference.mapcodes.length}: ${JSON.stringify(reference.mapcodes.map((m) => ({ mapcode: m.mapcode, territory: m.territory.toString() })))}\n` +
            `  actual   = #${results.length}: ${JSON.stringify(results.map((m) => ({ mapcode: m.getCode(precision), territory: m.getTerritory().toString() })))}`,
        );
        errors++;
      }

      // For every mapcode in the result set, check if it is contained in the reference set.
      for (const result of results) {
        let found = false;
        for (const referenceMapcodeRec of reference.mapcodes) {
          if (referenceMapcodeRec.territory === result.getTerritory()) {
            const indexOfDash = referenceMapcodeRec.mapcode.lastIndexOf("-");
            const endOfMapcode = indexOfDash + (precision > 0 ? precision + 1 : 0);
            if (referenceMapcodeRec.mapcode.length < endOfMapcode) {
              console.error(
                `checkFile: Reference mapcode not generated at highest precision: ${referenceMapcodeRec.mapcode}`,
              );
              errors++;
            }
            const referenceMapcode = referenceMapcodeRec.mapcode.substring(0, endOfMapcode);
            const generatedMapcode = result.getCode(precision);
            if (referenceMapcode === generatedMapcode) {
              found = true;
              break;
            }
          }
        }
        if (!found) {
          console.error(
            `checkFile: Created '${result.getCode(precision)} ${result.getTerritory()}' at ${reference.point} which is not present in the reference file!\n` +
              `reference=${JSON.stringify(reference.mapcodes.map((m) => ({ mapcode: m.mapcode, territory: m.territory.toString() })))}`,
          );
          errors++;
        }
      }

      // For every Mapcode in the reference set, check if it is contained in the result set.
      for (const referenceMapcodeRec of reference.mapcodes) {
        const indexOfDash = referenceMapcodeRec.mapcode.lastIndexOf("-");
        const endOfMapcode = indexOfDash + (precision > 0 ? precision + 1 : 0);
        const referenceMapcode = referenceMapcodeRec.mapcode.substring(0, endOfMapcode);

        let found = false;
        for (const result of results) {
          if (referenceMapcodeRec.territory === result.getTerritory()) {
            if (referenceMapcode === result.getCode(precision)) {
              found = true;
              break;
            }
          }
        }
        if (!found) {
          console.error(
            `checkFile: Found   '${referenceMapcodeRec.territory} ${referenceMapcodeRec.mapcode}' at ${reference.point} in reference file, not produced by new decoder!\n` +
              `reference=${JSON.stringify(reference.mapcodes.map((m) => ({ mapcode: m.mapcode, territory: m.territory.toString() })))}`,
          );
          errors++;
        }
      }

      // Check distance of decoded point to reference point for every requested precision.
      try {
        for (const referenceMapcodeRec of reference.mapcodes) {
          const indexOfDash = referenceMapcodeRec.mapcode.lastIndexOf("-");

          for (let p = checkAllDistances ? 0 : PRECISION_MAX; p < PRECISION_MAX; ++p) {
            const endOfMapcode = indexOfDash + (p > 0 ? p + 1 : 0);
            const cutOffReferenceMapcode = referenceMapcodeRec.mapcode.substring(0, endOfMapcode);

            // Decode cut-off mapcode to lat/lon.
            const result = decode(cutOffReferenceMapcode, referenceMapcodeRec.territory);

            // Get distance to reference point.
            const distanceM = Point.distanceInMeters(reference.point, result);
            deltaNm[p] = Math.max(deltaNm[p], distanceM * 1.0e6);

            // Check if the distance is no greater than the safe maximum specified.
            const maxDeltaM = Mapcode.getSafeMaxOffsetInMeters(p);
            if (distanceM > maxDeltaM) {
              console.error(
                `checkFile: Precision ${p}: mapcode ${referenceMapcodeRec.territory} ${referenceMapcodeRec.mapcode} ` +
                  `was generated for point ${reference.point}, but decodes to point ${result} which is ${distanceM} meters ` +
                  `from the original point (max is ${maxDeltaM} meters).`,
              );
              errors++;
            }
          }
        }
      } catch (e) {
        if (e instanceof UnknownMapcodeError) {
          console.error(
            `Mapcode was generated for point ${reference.point}, but cannot be decoded, msg=${e.message}`,
          );
          errors++;
        } else {
          throw e;
        }
      }
    }
  } finally {
    chunkedFile.close();
  }

  console.log(`checkFile: Total tasks executed: ${tasks} (file=${baseFileName})`);
  for (let p = checkAllDistances ? 0 : PRECISION_MAX; p < PRECISION_MAX; ++p) {
    const maxDeltaFoundMeters = deltaNm[p] / 1.0e6;
    const safeMaxOffsetInMeters = Mapcode.getSafeMaxOffsetInMeters(p);
    expect(maxDeltaFoundMeters, "Max delta is expected to be > 0").toBeGreaterThan(0.0);
    console.log(
      `checkFile: Precision ${p}: max found is ${maxDeltaFoundMeters} meters ` +
        `(absolute max is ${safeMaxOffsetInMeters} meters, delta is ${safeMaxOffsetInMeters - maxDeltaFoundMeters} meters)`,
    );
  }
  return errors;
}

describe("ReferenceFileTest", () => {
  it("checkRandomReferenceRecords", () => {
    let errors = 0;
    for (let i = 0; i < 8; ++i) {
      errors += checkFile(i, RANDOM_REFERENCE_FILE_1, false);
    }
    errors += checkFile(0, RANDOM_REFERENCE_FILE_2, false);
    errors += checkFile(0, RANDOM_REFERENCE_FILE_3, false);
    errors += checkFile(8, RANDOM_REFERENCE_FILE_2, false);
    errors += checkFile(8, RANDOM_REFERENCE_FILE_3, false);
    expect(errors, "Found errors").toBe(0);
  });

  it("checkGridReferenceRecords", () => {
    let errors = 0;
    for (let i = 0; i < 8; ++i) {
      errors += checkFile(i, GRID_REFERENCE_FILE_1, false);
    }
    errors += checkFile(0, GRID_REFERENCE_FILE_2, false);
    errors += checkFile(0, GRID_REFERENCE_FILE_3, false);
    errors += checkFile(8, GRID_REFERENCE_FILE_2, false);
    errors += checkFile(8, GRID_REFERENCE_FILE_3, false);
    expect(errors, "Found errors").toBe(0);
  });

  it("checkBoundariesReferenceRecords", () => {
    let errors = 0;
    errors += checkFile(0, BOUNDARIES_REFERENCE_FILE, false);
    errors += checkFile(8, BOUNDARIES_REFERENCE_FILE, true);
    expect(errors, "Found errors").toBe(0);
  });
});
